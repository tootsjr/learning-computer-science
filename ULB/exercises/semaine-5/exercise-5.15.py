def correcteur(mot: str, liste_mots: list[str]) -> str:
    correct_string = ""  # empty string variable that stores the end result
    similarities = (
        0  # variable that stores the highest amount of similarities after compairing
    )
    for i in range(len(liste_mots) - 1):
        temp_similar = (
            0  # temporary varible used to count current similarities in y loop
        )
        for y in range(
            min(len(mot) - 1, len(liste_mots[i]) - 1)
        ):  # we use min to not iterate over the index if one word is smaller than another
            if mot[y] == liste_mots[i][y]:  # if a character is the same, increment temp
                temp_similar += 1
        if (
            temp_similar > similarities
        ):  # if our current iteration had more similarities than our prior highest
            correct_string = liste_mots[i] 
            similarities = temp_similar

    return correct_string


